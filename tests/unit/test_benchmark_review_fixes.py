import tomllib
from pathlib import Path
from typing import ClassVar

import pytest
from pydantic import BaseModel, ConfigDict

from grantcompass.rules.benchmark import (
    BenchmarkManifestError,
    load_benchmark_cases,
)

FIXTURE_ROOT = Path(__file__).parents[1] / "fixtures" / "benchmark"
MANIFEST_PATH = FIXTURE_ROOT / "documents.jsonl"
SCRIPT_PATH = Path(__file__).parents[2] / "scripts" / "build_benchmark.py"


class _ScriptMetadata(BaseModel):
    model_config: ClassVar[ConfigDict] = ConfigDict(extra="ignore", frozen=True)

    dependencies: tuple[str, ...]


def _write_manifest_with_path(tmp_path: Path, fixture_path: str) -> Path:
    source = load_benchmark_cases(MANIFEST_PATH)[0]
    row = source.model_copy(update={"fixture_path": fixture_path})
    path = tmp_path / "documents.jsonl"
    _ = path.write_text(row.model_dump_json() + "\n", encoding="utf-8")
    return path


UNSAFE_FIXTURE_PATHS: tuple[str, ...] = (
    r"..\outside.pdf",
    r"documents\..\..\outside.pdf",
    r"C:\outside.pdf",
    r"\\server\share\outside.pdf",
    r"\\?\C:\outside.pdf",
    "../outside.pdf",
    "documents/./case.pdf",
    "documents//case.pdf",
)


@pytest.mark.parametrize("fixture_path", UNSAFE_FIXTURE_PATHS)
def test_benchmark_manifest_rejects_unsafe_fixture_path(
    tmp_path: Path,
    fixture_path: str,
) -> None:
    # Given: an untrusted manifest row with a non-canonical or escaping path.
    path = _write_manifest_with_path(tmp_path, fixture_path)

    # When: the manifest boundary resolves fixture paths.
    with pytest.raises(BenchmarkManifestError) as caught:
        _ = load_benchmark_cases(path)

    # Then: callers receive one finite path-safety code.
    assert caught.value.code == "unsafe_fixture_path"


def test_benchmark_manifest_accepts_normal_posix_fixture_path(tmp_path: Path) -> None:
    # Given: a canonical benchmark-local POSIX path.
    path = _write_manifest_with_path(tmp_path, "documents/case-01.hwpx")

    # When: the manifest boundary resolves fixture paths.
    cases = load_benchmark_cases(path)

    # Then: the normalized machine field is preserved.
    assert cases[0].fixture_path == "documents/case-01.hwpx"


def test_benchmark_script_pins_locked_pymupdf_version() -> None:
    # Given: the generator's machine-consumed PEP 723 metadata.
    lines = SCRIPT_PATH.read_text(encoding="utf-8").splitlines()
    start = lines.index("# /// script") + 1
    end = lines.index("# ///", start)

    # When: dependencies are read from the script environment contract.
    metadata = _ScriptMetadata.model_validate(
        tomllib.loads("\n".join(line.removeprefix("# ") for line in lines[start:end]))
    )

    # Then: PDF bytes are generated by the same exact version as the project lock.
    assert metadata.dependencies == ("pymupdf==1.28.0",)
